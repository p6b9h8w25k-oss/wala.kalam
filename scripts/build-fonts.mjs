// Packs the thmanyah WOFF2 files into js/fonts.generated.js.
//
// WHY: the thmanyah license permits web use only "as part of a compiled,
// packaged, or obfuscated product" and forbids serving the files so users can
// download them. So we do NOT ship font files; we ship one JS module holding
// lightly XOR-scrambled bytes that are rebuilt in memory at runtime.
// This is a deterrent, not security: confirm your exact use with thmanyah.
//
// Usage: node scripts/build-fonts.mjs "<path to 'thmanyah typeface' folder>"
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2];
if (!root) { console.error('Usage: node scripts/build-fonts.mjs "<thmanyah typeface dir>"'); process.exit(1); }

// [css family, weight, folder, file]
const FACES = [
  ['thmanyah Sans', 400, 'thmanyahsans', 'thmanyahsans-Regular'],
  ['thmanyah Sans', 500, 'thmanyahsans', 'thmanyahsans-Medium'],
  ['thmanyah Sans', 700, 'thmanyahsans', 'thmanyahsans-Bold'],
  ['thmanyah Sans', 900, 'thmanyahsans', 'thmanyahsans-Black'],
  ['thmanyah Display', 700, 'thmanyahserifdisplay', 'thmanyahserifdisplay-Bold'],
  ['thmanyah Display', 900, 'thmanyahserifdisplay', 'thmanyahserifdisplay-Black'],
];
const KEY = Buffer.from('wala-kalam-سيخ');
const out = FACES.map(([family, weight, dir, file]) => {
  const buf = readFileSync(join(root, dir, 'woff2', file + '.woff2'));
  const x = Buffer.alloc(buf.length);
  for (let i = 0; i < buf.length; i++) x[i] = buf[i] ^ KEY[i % KEY.length];
  return { family, weight, data: x.toString('base64') };
});
const js = `// GENERATED by scripts/build-fonts.mjs - do not edit.
// thmanyah typeface (c) 2026 thmanyah Publishing and Distribution. Used under the thmanyah Font License.
const KEY = new TextEncoder().encode('wala-kalam-سيخ');
const FACES = ${JSON.stringify(out)};
export async function loadFonts() {
  const jobs = FACES.map(async ({ family, weight, data }) => {
    const bin = atob(data); const b = new Uint8Array(bin.length);
    for (let i = 0; i < b.length; i++) b[i] = bin.charCodeAt(i) ^ KEY[i % KEY.length];
    const face = new FontFace(family, b.buffer, { weight: String(weight), display: 'block' });
    await face.load(); document.fonts.add(face);
  });
  await Promise.all(jobs);
}
`;
writeFileSync('js/fonts.generated.js', js);
console.log('wrote js/fonts.generated.js', (js.length / 1024).toFixed(0) + ' KB');
